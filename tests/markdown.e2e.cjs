'use strict';
const { _electron: electron } = require('playwright');
const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const os = require('node:os');
const { execFileSync } = require('node:child_process');
const { trustProject } = require('./ui-helpers.cjs');
const root = path.resolve(__dirname, '..'), directory = fs.mkdtempSync(path.join(os.tmpdir(), 'ade-markdown-'));
const repo = path.join(directory, 'repo'), bin = path.join(directory, 'bin');
fs.mkdirSync(bin); fs.mkdirSync(path.join(root, 'logs'), { recursive: true });
for (const provider of ['codex', 'claude']) { fs.copyFileSync(path.join(__dirname, 'fixtures', 'cli.cjs'), path.join(bin, provider)); fs.chmodSync(path.join(bin, provider), 0o755); }
execFileSync('git', ['init', '-b', 'main', repo], { stdio: 'ignore' });
let app;
async function run() {
  const executablePath = process.env.ADE_TEST_EXECUTABLE;
  app = await electron.launch({ ...(executablePath ? { executablePath, args: [] } : { args: [path.join(root, 'apps', 'desktop')] }), env: { ...process.env, PATH: bin + path.delimiter + process.env.PATH, ADE_USER_DATA: path.join(directory, 'user-data') } });
  const page = await app.firstWindow(), errors = [];
  page.on('pageerror', error => errors.push(error.message));
  await page.getByRole('heading', { name: 'Что будем делать?' }).waitFor();
  await app.evaluate(({ dialog, shell, clipboard }, repo) => { dialog.showOpenDialog = async () => ({ canceled: false, filePaths: [repo] }); shell.openExternal = async url => { globalThis.lastOpenedTestUrl = url; }; clipboard.writeText = value => { globalThis.copiedTestText = value; }; clipboard.readText = () => globalThis.copiedTestText; }, repo);
  await page.getByRole('button', { name: 'Подключить проект', exact: true }).click();
  await page.getByRole('textbox', { name: 'Задача', exact: true }).fill('[FIXTURE_STREAM]');
  await page.getByRole('button', { name: 'Сохранить задачу', exact: true }).click();
  await trustProject(page);
  await page.getByRole('button', { name: 'Запустить Codex', exact: true }).click();
  await page.getByRole('button', { name: 'Разрешить один раз', exact: true }).click();
  await page.getByRole('heading', { name: 'Потоковый ответ', exact: true }).waitFor();
  assert.notEqual(await page.locator('.local-task-phase').innerText(), 'Шаг завершён');
  await page.getByText('Поток ответа', { exact: true }).waitFor();
  await page.locator('.local-messages').evaluate(element => { element.scrollTop = 0; element.dispatchEvent(new Event('scroll')); });
  const initialLength = await page.locator('.local-markdown').evaluate(element => element.textContent.length);
  await page.waitForFunction(previous => document.querySelector('.local-markdown')?.textContent.length > previous + 15, initialLength);
  assert.equal(await page.locator('.local-messages').evaluate(element => element.scrollTop), 0);
  await page.locator('.local-code-block').waitFor();
  const codeNode = await page.locator('.local-code-block code').elementHandle();
  await page.screenshot({ path: path.join(root, 'logs', 'markdown-streaming.png') });
  await page.waitForFunction(() => document.querySelector('.local-task-phase')?.textContent === 'Шаг завершён');
  assert.equal(await codeNode.evaluate(element => element.isConnected), true);
  const markdown = page.locator('.local-markdown');
  assert.equal(await markdown.locator('strong').filter({ hasText: 'ответ готов' }).count(), 1);
  assert.equal(await markdown.locator('li').count(), 2);
  assert.equal(await markdown.locator('table td').count(), 2);
  assert.equal(await markdown.locator('blockquote').innerText(), 'Цитата');
  assert.ok(await markdown.locator('.token.keyword').count());
  assert.equal(await markdown.locator('img,iframe,script,svg').count(), 0);
  assert.equal(await page.evaluate(() => window.injected), undefined);
  assert.equal(await markdown.locator('a[href^="javascript:"]').count(), 0);
  await page.getByRole('button', { name: 'Копировать код', exact: true }).click();
  await page.getByRole('button', { name: 'Код скопирован', exact: true }).waitFor();
  assert.equal(await app.evaluate(({ clipboard }) => clipboard.readText()), 'const answer = 42;\nconsole.log(answer);');
  await page.getByRole('link', { name: 'Документация', exact: true }).click();
  assert.equal(await app.evaluate(() => globalThis.lastOpenedTestUrl), 'https://example.com/docs');
  const denied = await page.evaluate(() => window.ade.openExternal('javascript:alert(1)'));
  assert.equal(denied.ok, false);
  await page.getByRole('button', { name: 'Настройки', exact: true }).click();
  await page.getByRole('combobox', { name: 'Тема', exact: true }).selectOption('light');
  await page.getByRole('button', { name: 'Задачи', exact: true }).click();
  await page.getByRole('button', { name: /FIXTURE_STREAM/ }).click();
  await page.locator('.local-code-block').waitFor();
  await page.screenshot({ path: path.join(root, 'logs', 'markdown-light.png') });
  await app.evaluate(({ BrowserWindow }) => { const win = BrowserWindow.getAllWindows()[0]; win.setMinimumSize(320, 480); win.setSize(390, 720); });
  assert.equal(await page.evaluate(() => document.documentElement.scrollWidth > innerWidth), false);
  assert.deepEqual(errors, []);
  fs.writeFileSync(path.join(root, 'logs', 'markdown-verification.json'), JSON.stringify({ passed: true, packaged: !!executablePath, checks: ['partial Markdown visible before completion', 'unfinished code fence renders while streaming', 'scroll position and code DOM persist across chunks', 'headings/emphasis/lists/tables/quotes/highlighting', 'raw HTML and dangerous links inert; no remote images', 'copy exact code and explicit HTTP link', 'both themes and narrow layout'], errors }, null, 2));
  console.log('PASS Markdown: partial stream, stable scroll/DOM, syntax, tables, copy and safe links.');
}
run().catch(async error => { if(app) { try { const page=await app.firstWindow();await page.screenshot({path:path.join(root,'logs','markdown-failure.png')});fs.writeFileSync(path.join(root,'logs','markdown-failure.json'),JSON.stringify(await page.evaluate(async()=>({checkboxes:[...document.querySelectorAll('input[type=checkbox]')].map(el=>({checked:el.checked,disabled:el.disabled,label:el.parentElement.textContent})),state:await window.ade.call('bootstrap',{}),text:document.body.innerText})),null,2)); } catch {} } console.error(error); process.exitCode = 1; }).finally(async () => { if (app) await app.close(); fs.rmSync(directory, { recursive: true, force: true }); });
